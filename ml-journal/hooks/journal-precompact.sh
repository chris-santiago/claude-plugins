#!/usr/bin/env bash
# journal-precompact.sh — Auto-write checkpoint to journal before compaction
#
# Fires on PreCompact hook (before Claude Code runs /compact).
# Reads trigger and custom_instructions from stdin JSON.
# Writes a checkpoint entry to .project-log/journal.jsonl.
# Exits silently on any error — never blocks compaction.

set -euo pipefail

# --- Parse stdin ---
INPUT="$(cat)"

TRIGGER="$(echo "$INPUT" | jq -r '.trigger // "auto"' 2>/dev/null || true)"
TRIGGER="${TRIGGER:-auto}"
CUSTOM_INSTRUCTIONS="$(echo "$INPUT" | jq -r '.custom_instructions // ""' 2>/dev/null || true)"

# shellcheck source=journal-hook-lib.sh
source "$(dirname "${BASH_SOURCE[0]}")/journal-hook-lib.sh"
journal_hook_init

# --- Get git state ---
BRANCH="$(git branch --show-current 2>/dev/null || true)"
[ -n "$BRANCH" ] || BRANCH="detached@$(git rev-parse --short HEAD 2>/dev/null || echo unknown)"

# Porcelain -z output is NUL-separated and never quoted, so paths with spaces
# survive intact. Each record is "XY path"; a rename or copy is followed by an
# extra record holding the old path, which is consumed and discarded.
MODIFIED=""
while IFS= read -r -d '' record; do
    status="${record:0:2}"
    MODIFIED="${MODIFIED:+$MODIFIED,}${record:3}"
    if [[ "$status" == *[RC]* ]]; then
        IFS= read -r -d '' _ || true
    fi
done < <(git --no-optional-locks -c core.fsmonitor=false status --porcelain -z 2>/dev/null || true)
# core.fsmonitor in a repo's .git/config names a command git would run here;
# overriding it keeps git status from executing anything the repo supplies.

if [ -n "$MODIFIED" ] || [ "$BRANCH" != "main" ]; then
    GIT_STATE="branch: $BRANCH"
    [ -n "$MODIFIED" ] && GIT_STATE="$GIT_STATE | modified: $MODIFIED"
else
    GIT_STATE=""
fi

# --- Build in_progress note ---
IN_PROGRESS="Auto-captured at PreCompact (trigger: $TRIGGER)."
if [ -n "$CUSTOM_INSTRUCTIONS" ]; then
    IN_PROGRESS="$IN_PROGRESS User compact note: $CUSTOM_INSTRUCTIONS"
fi

# --- Write checkpoint ---
ARGS=(
    --type checkpoint
    --in-progress "$IN_PROGRESS"
    --key-context "This checkpoint was auto-generated by the PreCompact hook. Use /resume to load it. Run /checkpoint manually for a richer synthesis."
)

[ -n "$GIT_STATE" ] && ARGS+=(--git-state "$GIT_STATE")

python3 -I "$SCRIPTS_DIR/journal_log.py" "${ARGS[@]}" >/dev/null 2>&1 || exit 0

exit 0
